package com.campusride.dao;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import com.campusride.model.User;

/**
 * SQL for the users table. DAO = "Data Access Object": it only runs SQL,
 * it does NOT decide business rules (that is the service layer's job).
 *
 * Every DAO method receives the Connection from the service. This lets a
 * service run several DAO methods inside ONE transaction (same connection).
 */
public class UserDAO {

    /** Returns the user with this username, or null if none. */
    public User findByUsername(Connection con, String username) throws SQLException {
        String sql = "SELECT user_id, username, password_hash, password_salt, role, created_at "
                   + "FROM users WHERE username = ?";
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, username);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next() ? map(rs) : null;
            }
        }
    }

    /** True if the username is already taken. */
    public boolean usernameExists(Connection con, String username) throws SQLException {
        String sql = "SELECT 1 FROM users WHERE username = ?";
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, username);
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next();
            }
        }
    }

    /** INSERTs a user and returns the new user_id generated by MySQL. */
    public int insert(Connection con, User u) throws SQLException {
        String sql = "INSERT INTO users (username, password_hash, password_salt, role) VALUES (?, ?, ?, ?)";
        try (PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setString(1, u.getUsername());
            ps.setString(2, u.getPasswordHash());
            ps.setString(3, u.getPasswordSalt());
            ps.setString(4, u.getRole());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                keys.next();
                return keys.getInt(1);
            }
        }
    }

    /** Copies one ResultSet row into a User object. */
    private User map(ResultSet rs) throws SQLException {
        User u = new User();
        u.setUserId(rs.getInt("user_id"));
        u.setUsername(rs.getString("username"));
        u.setPasswordHash(rs.getString("password_hash"));
        u.setPasswordSalt(rs.getString("password_salt"));
        u.setRole(rs.getString("role"));
        u.setCreatedAt(rs.getTimestamp("created_at").toLocalDateTime());
        return u;
    }
}
